// Generates src/engine/preflop-table.js: the preflop equity of every one of
// the 169 starting-hand classes against 1..8 random opponents, plus a
// strength ordering used for `top_pct` / `top(n)` in the bot language.
//
//   node tools/gen-preflop.mjs [iterations]   (default 6000 per cell)

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { allHandClasses, classCombos, RANKS } from '../src/engine/cards.js';
import { equityMonteCarlo } from '../src/engine/montecarlo.js';
import { makeRng } from '../src/util.js';

const ITER = Number(process.argv[2]) || 6000;
const rng = makeRng('preflop-table-v1');
const classes = allHandClasses();

function sampleCards(cls) {
  const a = RANKS.indexOf(cls[0]), b = RANKS.indexOf(cls[1]);
  if (cls.length === 2) return [a * 4 + 0, b * 4 + 1];
  return cls[2] === 's' ? [a * 4 + 0, b * 4 + 0] : [a * 4 + 0, b * 4 + 1];
}

const equity = {};
const t0 = Date.now();
for (const cls of classes) {
  const hole = sampleCards(cls);
  equity[cls] = [];
  for (let opp = 1; opp <= 8; opp++) {
    equity[cls].push(Number(equityMonteCarlo(hole, [], opp, ITER, rng).toFixed(4)));
  }
}

// Strength order: average "share over fair share" heads-up, 3-way and 5-way,
// which ranks suited connectors more sensibly than heads-up equity alone.
const score = (cls) => (equity[cls][0] * 2 + equity[cls][1] * 3 + equity[cls][3] * 5) / 3;
const order = classes.slice().sort((x, y) => score(y) - score(x));
const topPct = {};
let cum = 0;
for (const cls of order) {
  cum += classCombos(cls);
  topPct[cls] = Number(((cum / 1326) * 100).toFixed(2));
}

const out = `// GENERATED by tools/gen-preflop.mjs (${ITER} Monte Carlo deals per cell). Do not edit.
// PREFLOP_EQUITY[cls][k] = equity of class cls against k+1 random opponents.
// TOP_PCT[cls] = percent of all 1326 starting hands at least as strong as cls.

export const PREFLOP_EQUITY = ${JSON.stringify(equity)};

export const PREFLOP_ORDER = ${JSON.stringify(order)};

export const TOP_PCT = ${JSON.stringify(topPct)};
`;
writeFileSync(fileURLToPath(new URL('../src/engine/preflop-table.js', import.meta.url)), out);
console.log(`Wrote preflop table in ${((Date.now() - t0) / 1000).toFixed(1)}s. Top 10: ${order.slice(0, 10).join(' ')}`);
console.log('Bottom 5:', order.slice(-5).join(' '));
